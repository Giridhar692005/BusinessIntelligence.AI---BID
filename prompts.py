# NARRATIVE USER PROMPT
# =========================================================

def build_narrative_user_prompt(
    report,
    evidence=None
):
    """
    Builds the user prompt containing the actual
    statistical report and optional retrieved evidence.
    """

    should_abstain = (

        report
        .get(
            "confidence",
            {}
        )
        .get(
            "should_abstain",
            False
        )
    )


    base = f"""
Here is the structured business analysis generated by
the statistical analysis engine.

Use this information as the factual basis of your answer.

STATISTICAL REPORT:

{json.dumps(
    report,
    indent=2,
    default=str
)}
"""


    # -----------------------------------------------------
    # Supporting evidence
    # -----------------------------------------------------

    evidence_block = ""


    if evidence and evidence.get(
        "evidence"
    ):

        lines = [

            """

SUPPORTING RETRIEVED EVIDENCE:

Use this evidence only when it genuinely supports
the statistical analysis.

Do not invent statements or quotations.

"""
        ]


        for item in evidence["evidence"]:

            item_date = item.get(
                "date",
                "unknown"
            )

            source = item.get(
                "source",
                "unknown"
            )

            text = item.get(
                "text",
                ""
            )

            lines.append(
                f"- ({item_date}, {source}): "
                f"\"{text}\""
            )


        evidence_block = (
            "\n".join(lines)
            +
            "\n"
        )


    # -----------------------------------------------------
    # Abstention
    # -----------------------------------------------------

    if should_abstain:

        instructions = """

The statistical engine has low confidence in its
explanation.

Do NOT provide a confident causal explanation.

Instead:

1. State what changed.

2. State that the available evidence is not sufficient
   to identify one reliable cause.

3. Explain the uncertainty using the supplied confidence
   information.

4. Suggest what additional data or manual investigation
   would help resolve the issue.

Do not invent missing information.

"""

    else:

        instructions = """

Write a concise business explanation.

The explanation should:

1. State what happened to the affected KPI: the size and
   direction of the change (use the pct_change and
   absolute_change from target_kpi_movement).

2. State clearly whether that movement was favorable,
   unfavorable, or neutral for the business -- using ONLY
   the supplied business_impact label. Never decide this
   yourself. If business_impact is "unknown", say plainly
   that whether this counts as a gain or a loss isn't
   established for this KPI, rather than guessing.

3. If the report includes a "net_profit_snapshot" with a
   net_profit value, state that exact dollar figure and
   whether it was a profit or a loss for that day. Do not
   round it into vague language like "healthy" -- give the
   number.

4. Identify the strongest statistical driver.

5. Explain the driver's contribution in plain business
   language.

6. Mention other affected KPIs only when relevant.

7. Use retrieved evidence only when it supports the
   analysis.

8. End with one practical next step when appropriate.

Do not claim certainty beyond the supplied evidence.

"""

    return (
        base
        +
        evidence_block
        +
        instructions
    )


